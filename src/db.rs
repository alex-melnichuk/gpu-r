//! Reference specification database.
//!
//! These are the *factory* specs of each SKU. Everything the driver/VBIOS
//! reports is compared against them: a mismatch is how BIOS-modded,
//! unlocked, re-labelled (fake) or memory-modded cards are detected.
//!
//! One PCI device ID is often shared by several SKUs (e.g. Navi 21 =
//! RX 6800 / 6800 XT / 6900 XT). The SKU is then picked by PCI revision,
//! and if the revision is unknown, by the number of active compute units.

use serde::{Deserialize, Serialize};
use std::sync::OnceLock;

/// Memory technology as named by the spec source ("GDDR6", "HBM2", ...).
#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
pub struct MemType(pub &'static str);

impl MemType {
    pub fn name(&self) -> &'static str {
        self.0
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct Spec {
    pub vendor: u16,
    pub device: u16,
    /// PCI revision that identifies this SKU (None = any).
    pub rev: Option<u8>,
    pub name: &'static str,
    pub chip: &'static str,
    /// Compute units (AMD) / streaming multiprocessors (NVIDIA).
    pub units: u32,
    /// Largest unit count shipped on this chip (full die or best bin).
    pub units_full_die: u32,
    pub shaders: u32,
    pub tmus: u32,
    pub rops: u32,
    pub bus_width: u32,
    pub mem: MemType,
    /// Factory memory sizes in MiB.
    pub mem_sizes_mb: &'static [u32],
    /// Reference memory data rate (Gbps per pin), derived from bandwidth / bus width.
    pub mem_gbps: f32,
    pub boost_mhz: u32,
    pub process: &'static str,
    pub die_mm2: u32,
    pub transistors_m: u32,
    pub release: &'static str,
    /// AMD graphics core IP version (from IP discovery), e.g. (10,3,0).
    pub gc_ip: Option<(u8, u8, u8)>,
    /// NVIDIA CUDA compute capability.
    pub cuda_cc: Option<(u8, u8)>,
    /// All internal consistency checks of the published numbers passed.
    pub verified: bool,
    pub checks: &'static [&'static str],
    pub spec_source: &'static str,
    pub id_sources: &'static [&'static str],
}

impl Spec {
    /// Does a VRAM size (bytes, as the driver reports it) match a factory configuration?
    /// Drivers report slightly less than the nominal size, so allow 3 %.
    pub fn size_matches(&self, bytes: u64) -> bool {
        let mb = bytes as f64 / (1u64 << 20) as f64;
        self.mem_sizes_mb.iter().any(|&s| (mb - s as f64).abs() <= s as f64 * 0.03)
    }

    pub fn sizes_str(&self) -> String {
        self.mem_sizes_mb
            .iter()
            .map(|&m| if m >= 1024 && m % 1024 == 0 { format!("{} GB", m / 1024) } else if m >= 1024 { format!("{:.1} GB", m as f64 / 1024.0) } else { format!("{m} MB") })
            .collect::<Vec<_>>()
            .join(" / ")
    }
}

/// Generated by tools/build_gpudb.py; see that file for the sources.
const DB_JSON: &str = include_str!("../assets/gpudb.json");

#[derive(Deserialize)]
struct Row {
    vendor: u16,
    name: String,
    chip: String,
    ids: Vec<(u16, Option<u8>)>,
    shaders: u32,
    tmus: u32,
    rops: u32,
    units: u32,
    units_full_die: u32,
    bus_width: u32,
    mem: String,
    mem_sizes_mb: Vec<u32>,
    mem_gbps: f32,
    boost_mhz: u32,
    process: String,
    die_mm2: u32,
    transistors_m: u32,
    release: String,
    gc_ip: Option<(u8, u8, u8)>,
    cuda_cc: Option<(u8, u8)>,
    verified: bool,
    checks: Vec<String>,
    spec_source: String,
    id_sources: Vec<String>,
}

#[derive(Deserialize)]
struct DbFile {
    gpus: Vec<Row>,
}

fn leak(s: String) -> &'static str {
    Box::leak(s.into_boxed_str())
}

fn leak_list(v: Vec<String>) -> &'static [&'static str] {
    Box::leak(v.into_iter().map(leak).collect::<Vec<_>>().into_boxed_slice())
}

/// Every (device ID, revision) -> SKU entry of the reference database.
pub fn all() -> &'static [Spec] {
    static DB: OnceLock<Vec<Spec>> = OnceLock::new();
    DB.get_or_init(|| {
        let f: DbFile = match serde_json::from_str(DB_JSON) {
            Ok(f) => f,
            Err(e) => {
                eprintln!("reference database is corrupt: {e}");
                return vec![];
            }
        };
        let mut out = vec![];
        for r in f.gpus {
            let name = leak(r.name);
            let chip = leak(r.chip);
            let mem = MemType(leak(r.mem));
            let sizes: &'static [u32] = Box::leak(r.mem_sizes_mb.into_boxed_slice());
            let process = leak(r.process);
            let release = leak(r.release);
            let checks = leak_list(r.checks);
            let spec_source = leak(r.spec_source);
            let id_sources = leak_list(r.id_sources);
            for (device, rev) in r.ids {
                out.push(Spec {
                    vendor: r.vendor,
                    device,
                    rev,
                    name,
                    chip,
                    units: r.units,
                    units_full_die: r.units_full_die,
                    shaders: r.shaders,
                    tmus: r.tmus,
                    rops: r.rops,
                    bus_width: r.bus_width,
                    mem,
                    mem_sizes_mb: sizes,
                    mem_gbps: r.mem_gbps,
                    boost_mhz: r.boost_mhz,
                    process,
                    die_mm2: r.die_mm2,
                    transistors_m: r.transistors_m,
                    release,
                    gc_ip: r.gc_ip,
                    cuda_cc: r.cuda_cc,
                    verified: r.verified,
                    checks,
                    spec_source,
                    id_sources,
                });
            }
        }
        out
    })
}

#[derive(Debug, Clone, Serialize)]
pub struct DbMatch {
    pub spec: Spec,
    /// How the SKU was selected.
    pub how: &'static str,
    /// All SKUs that share this device ID.
    pub candidates: Vec<String>,
}

pub fn lookup(vendor: u16, device: u16, rev: Option<u8>, active_units: Option<u32>) -> Option<DbMatch> {
    let cands: Vec<Spec> = all()
        .iter()
        .filter(|s| s.vendor == vendor && s.device == device)
        .cloned()
        .collect();
    if cands.is_empty() {
        return None;
    }
    let mut names: Vec<String> = vec![];
    for s in &cands {
        if !names.iter().any(|n| n == s.name) {
            names.push(s.name.to_string());
        }
    }
    if names.len() == 1 {
        return Some(DbMatch { spec: cands[0].clone(), how: "device ID", candidates: names });
    }
    if let Some(s) = rev.and_then(|r| cands.iter().find(|s| s.rev == Some(r))) {
        return Some(DbMatch { spec: s.clone(), how: "device ID + PCI revision", candidates: names });
    }
    if let Some(u) = active_units {
        let m: Vec<&Spec> = cands.iter().filter(|s| s.units == u).collect();
        if m.len() == 1 {
            return Some(DbMatch { spec: m[0].clone(), how: "device ID + active unit count", candidates: names });
        }
        if let Some(s) = m.first() {
            return Some(DbMatch {
                spec: (*s).clone(),
                how: "device ID + unit count (several SKUs share this config)",
                candidates: names,
            });
        }
    }
    Some(DbMatch { spec: cands[0].clone(), how: "device ID only (ambiguous!)", candidates: names })
}
